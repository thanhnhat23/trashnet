"""Generate web CSS tokens and Dart theme/labels from the shared JSON files."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared"


def hex_to_dart(h: str) -> str:
    return "Color(0xFF" + h.lstrip("#").upper() + ")"


def css(tokens: dict, labels: dict) -> str:
    def block(sel: str, c: dict) -> str:
        body = "\n".join(f"  --{k}: {v};" for k, v in c.items())
        return f"{sel} {{\n{body}\n}}\n"

    out = ["/* Generated by shared/gen_tokens.py. Do not edit. */\n"]
    out.append(":root {\n"
               f"  --font-sans: {tokens['font']['sans']};\n"
               f"  --font-mono: {tokens['font']['mono']};\n"
               f"  --radius: {tokens['radius']}px;\n"
               + "".join(f"  --s{i + 1}: {v}px;\n" for i, v in enumerate(tokens["space"]))
               + "".join(f"  --fs-{k}: {v}px;\n" for k, v in tokens["size"].items())
               + "".join(f"  --bin-{b['id']}: {b['color']};\n" for b in labels["bins"])
               + "}\n")
    out.append(block(":root, [data-theme='light']", tokens["color"]["light"]))
    out.append(block("[data-theme='dark']", tokens["color"]["dark"]))
    out.append("@media (prefers-color-scheme: dark) {\n"
               + block(":root:not([data-theme='light'])", tokens["color"]["dark"]).replace("\n", "\n  ").rstrip()
               + "\n}\n")
    return "\n".join(out)


def dart_tokens(tokens: dict) -> str:
    def palette(name: str, c: dict) -> str:
        fields = "\n".join(f"  final Color {k};" for k in c)
        ctor = ", ".join(f"required this.{k}" for k in c)
        vals = ",\n    ".join(f"{k}: {hex_to_dart(v)}" for k, v in c.items())
        return (f"class {name} {{\n{fields}\n  const {name}({{{ctor}}});\n"
                f"  static const light = {name}(\n    "
                + ",\n    ".join(f"{k}: {hex_to_dart(v)}" for k, v in tokens['color']['light'].items())
                + ");\n"
                f"  static const dark = {name}(\n    "
                + ",\n    ".join(f"{k}: {hex_to_dart(v)}" for k, v in tokens['color']['dark'].items())
                + ");\n}\n")

    return ("// Generated by shared/gen_tokens.py. Do not edit.\n"
            "import 'package:flutter/painting.dart';\n\n"
            + palette("TnPalette", tokens["color"]["light"])
            + f"\nconst double tnRadius = {tokens['radius']}.0;\n"
            + "const List<double> tnSpace = ["
            + ", ".join(f"{v}.0" for v in tokens["space"]) + "];\n"
            + "".join(f"const double tnFs{k.capitalize()} = {v}.0;\n" for k, v in tokens["size"].items()))


def dart_labels(labels: dict) -> str:
    rows = ",\n  ".join(
        "TnBin(id: '{id}', bin: {bin}, nameVi: '{name_vi}', nameEn: '{name_en}', "
        "color: {color}, tips: '{tips}')".format(
            color=hex_to_dart(b["color"]), **{k: v.replace("'", "\\'") if isinstance(v, str) else v
                                                for k, v in b.items() if k != "color"})
        for b in labels["bins"])
    return ("// Generated by shared/gen_tokens.py. Do not edit.\n"
            "import 'package:flutter/painting.dart';\n\n"
            "class TnBin {\n"
            "  final String id;\n  final int bin;\n  final String nameVi;\n  final String nameEn;\n"
            "  final Color color;\n  final String tips;\n"
            "  const TnBin({required this.id, required this.bin, required this.nameVi,\n"
            "      required this.nameEn, required this.color, required this.tips});\n}\n\n"
            f"const List<TnBin> tnBins = [\n  {rows},\n];\n\n"
            "TnBin tnBinById(String id) =>\n"
            "    tnBins.firstWhere((b) => b.id == id, orElse: () => tnBins[2]);\n")


def main() -> None:
    tokens = json.loads((SHARED / "design-tokens.json").read_text("utf-8"))
    labels = json.loads((SHARED / "labels.json").read_text("utf-8"))
    targets = {
        ROOT / "server/web/src/styles/tokens.css": css(tokens, labels),
        ROOT / "mobile/lib/core/theme/tokens.dart": dart_tokens(tokens),
        ROOT / "mobile/lib/core/labels.dart": dart_labels(labels),
    }
    for path, text in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, "utf-8")
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
